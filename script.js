var sharedACtx = null;
function getSharedCtx() {
    if (!sharedACtx) sharedACtx = new (window.AudioContext || window.webkitAudioContext)();
    if (sharedACtx.state === 'suspended') sharedACtx.resume();
    return sharedACtx;
}
// Warm up the context immediately on first pointer interaction
document.addEventListener('pointerdown', getSharedCtx, { once: true });

function playTileClick() {
    try {
        var c = getSharedCtx();
        var t = c.currentTime;
        var osc = c.createOscillator();
        var env = c.createGain();
        osc.type = 'sine';
        osc.frequency.setValueAtTime(600, t);
        osc.frequency.exponentialRampToValueAtTime(200, t + 0.07);
        env.gain.setValueAtTime(0.22, t);
        env.gain.exponentialRampToValueAtTime(0.0001, t + 0.08);
        osc.connect(env).connect(c.destination);
        osc.start(t);
        osc.stop(t + 0.08);
    } catch(e) {}
}

// Toned down "soft" click for projects
function playSoftClick() {
    try {
        var c = getSharedCtx();
        var t = c.currentTime;
        var osc = c.createOscillator();
        var env = c.createGain();
        osc.type = 'sine';
        osc.frequency.setValueAtTime(400, t); // Lower pitch
        osc.frequency.exponentialRampToValueAtTime(150, t + 0.1);
        env.gain.setValueAtTime(0.08, t);      // Much lower volume (toned down)
        env.gain.exponentialRampToValueAtTime(0.0001, t + 0.1);
        osc.connect(env).connect(c.destination);
        osc.start(t);
        osc.stop(t + 0.1);
    } catch(e) {}
}

